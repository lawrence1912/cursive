/**
 * 「跳到行」的查询解析（0.2.x）。
 *
 * ⌘T 那个面板此前只认文件名，而「第几行」是长文里最常用的一种定位 ——
 * 跨文件搜索的结果里带着行号、编译器/评审意见里也都是 `文件:行` 这种写法，
 * 复制过来能直接用才算接得上。
 *
 * 两种写法：
 *   · `:120`        —— 当前文档的第 120 行
 *   · `readme:120`  —— 那个文件的第 120 行（文件名照旧模糊匹配）
 *
 * 单独拿出来当纯函数是为了**能被测**：`main.ts` 是入口、进不了 node 测试，
 * 而这条路上会错的全在这几行正则里。
 */

export interface Goto {
  /** 冒号前那一截（已 trim）。空串 = 没写文件名，跳的是当前文档 */
  name: string
  /** 行号，1 起。这里只保证是正整数，越界由跳转那一侧夹 */
  line: number
}

/**
 * 认得出 `…:数字` 就回一份，否则 null（= 这次查询与行号无关，照旧只匹配文件名）。
 *
 * 三条边界都在这儿收：
 * - **末尾必须是数字**：`a:b` 不是跳行，`http://x` 更不是（冒号后面不是纯数字）；
 * - `:0` 与 `:007` 都收下（夹到第 1 行、认成第 7 行）—— 用户从别处复制来的行号
 *   带前导零是常事，为这个报错没道理；
 * - Windows 盘符那种 `C:\\x` 不必特判：冒号后面不是纯数字，第一条就挡住了。
 */
export function parseGoto(raw: string): Goto | null {
  const m = /^(.*?):(\d+)$/.exec(raw.trim())
  if (!m) return null
  return { name: m[1]!.trim(), line: Math.max(1, Number(m[2])) }
}
